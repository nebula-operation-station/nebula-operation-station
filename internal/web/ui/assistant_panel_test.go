// Tabs switch without htmx and with it: the link of the active tab is
// marked aria-selected, and a request without htmx gets the full layout.
func TestAssistantTabsMarkActiveAndWorkWithoutHTMX(t *testing.T) {
	store := &fakeOpsStore{}
	h := assistantServer(t, assistantOps(store, newCatalog()), assistantUser{"root"})
	selected := func(label string) *regexp.Regexp {
		return regexp.MustCompile(`aria-selected="true"[^>]*>` + label + `</a>`)
	}
	cases := []struct {
		path   string
		htmx   bool
		active string
	}{
		{"/assistant/ops", true, "Ops"},
		{"/assistant/help", true, "Help"},
		{"/assistant/ops", false, "Ops"},
		{"/assistant/help", false, "Help"},
	}
	for _, tc := range cases {
		var headers map[string]string
		if tc.htmx {
			headers = map[string]string{"HX-Request": "true"}
		}
		rec := doAssistant(t, h, http.MethodGet, tc.path, headers)
		body := rec.Body.String()
		if !selected(tc.active).MatchString(body) {
			t.Errorf("GET %s (htmx=%v): tab %s not aria-selected", tc.path, tc.htmx, tc.active)
		}
		if got := strings.Count(body, `aria-selected="true"`); got != 1 {
			t.Errorf("GET %s (htmx=%v): %d tabs selected, want 1", tc.path, tc.htmx, got)
		}
		isPage := strings.Contains(body, "<html")
		if isPage == tc.htmx {
			t.Errorf("GET %s (htmx=%v): full page=%v, want %v", tc.path, tc.htmx, isPage, !tc.htmx)
		}
		if tc.htmx && !strings.Contains(body, `id="assistant-panel"`) {
			t.Errorf("GET %s: htmx response is not the panel", tc.path)
		}
	}
}

