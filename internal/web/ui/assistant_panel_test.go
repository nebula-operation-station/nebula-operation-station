// sessionAssistantServer serves the UI behind the real session layer, with
// AssistantOps.User left nil so the default path (auth.SessionFrom) decides.
// It returns the handler and a function that makes a session cookie for user.
func sessionAssistantServer(t *testing.T, store *fakeOpsStore) (http.Handler, func(user string) *http.Cookie) {
	t.Helper()
	db, err := serverdb.Open(filepath.Join(t.TempDir(), "server.db"))
	if err != nil {
		t.Fatalf("serverdb.Open: %v", err)
	}
	t.Cleanup(func() { _ = db.Close() })
	sessions := auth.NewStore(db, time.Now)
	log := slog.New(slog.NewTextHandler(io.Discard, nil))
	a, err := auth.New(auth.Options{Executor: pveFakeExec{}, Sessions: sessions, Log: log})
	if err != nil {
		t.Fatalf("auth.New: %v", err)
	}
	o := &ui.AssistantOps{Store: store, IsAdmin: isAdminName, Catalog: newCatalog()}
	srv, err := newTestHandler(t, ui.Options{PublicOrigin: assistantOrigin, AssistantOps: o}).Server()
	if err != nil {
		t.Fatalf("Server: %v", err)
	}
	h := middleware.Handler(middleware.Options{PublicOrigin: assistantOrigin}, a.Wrap(srv.Handler))
	cookie := func(user string) *http.Cookie {
		t.Helper()
		token, _, err := sessions.Create(context.Background(), "cred-"+user, user)
		if err != nil {
			t.Fatalf("create session: %v", err)
		}
		return &http.Cookie{Name: auth.CookieName, Value: token}
	}
	return h, cookie
}

// Through the real session layer: the admin gets the Ops routes and the
// tab, a logged-in non-admin gets 404 and no tab, and no session gets no
// Ops content either.
func TestAssistantOpsDefaultSessionPathDecidesAdmin(t *testing.T) {
	store := &fakeOpsStore{notes: []opsnotes.Note{fixNote(1, time.Unix(0, 0), snapshotOpenSSL, opsnotes.Body{Summary: "x"})}}
	h, cookie := sessionAssistantServer(t, store)
	get := func(path string, c *http.Cookie) *httptest.ResponseRecorder {
		t.Helper()
		req := httptest.NewRequest(http.MethodGet, path, nil)
		req.Header.Set("HX-Request", "true")
		if c != nil {
			req.AddCookie(c)
		}
		rec := httptest.NewRecorder()
		h.ServeHTTP(rec, req)
		return rec
	}

	if rec := get("/assistant/ops", cookie("root")); rec.Code != http.StatusOK || !strings.Contains(rec.Body.String(), "openssl") {
		t.Errorf("admin GET /assistant/ops = %d, want 200 with the card", rec.Code)
	}
	if body := get("/assistant/panel", cookie("root")).Body.String(); !strings.Contains(body, ">Ops</a>") {
		t.Error("admin panel should list the Ops tab")
	}

	if rec := get("/assistant/ops", cookie("alice")); rec.Code != http.StatusNotFound {
		t.Errorf("non-admin GET /assistant/ops = %d, want 404", rec.Code)
	}
	if body := get("/assistant/panel", cookie("alice")).Body.String(); strings.Contains(body, ">Ops</a>") {
		t.Error("non-admin panel lists the Ops tab")
	}
	if rec := get("/assistant/ops/notes/1", cookie("alice")); rec.Code != http.StatusNotFound {
		t.Errorf("non-admin note detail = %d, want 404", rec.Code)
	}

	if rec := get("/assistant/ops", nil); rec.Code == http.StatusOK || strings.Contains(rec.Body.String(), "openssl") {
		t.Errorf("no session GET /assistant/ops = %d, want refusal without card", rec.Code)
	}
	if n := store.readCount(); n == 0 {
		t.Error("admin Ops requests should read the store")
	}
}
