// The LLM label of a section that shows model text (ADR 0016 D8).
const (
	llmLabelEN = "Generated by an LLM – unverified."
	llmLabelDE = "Von einem LLM erzeugt – ungeprüft."
)

// sectionOf returns the markup of the section with aria-label label, up to
// its closing tag. ok is false when there is no such section.
func sectionOf(body, label string) (string, bool) {
	start := strings.Index(body, `aria-label="`+label+`"`)
	if start < 0 {
		return "", false
	}
	end := strings.Index(body[start:], "</section>")
	if end < 0 {
		return "", false
	}
	return body[start : start+end], true
}

// modelTextCard is a note whose every model-text field is filled, so every
// section that shows model text is rendered.
func modelTextCard() opsnotes.Note {
	const evil = `<img src=x onerror=alert(3)>`
	return fixNote(1, time.Unix(0, 0), snapshotOpenSSL, opsnotes.Body{
		Summary:     "summary text",
		Urgency:     "soon",
		Steps:       []opsnotes.StepInput{{ActionID: "package.install_security", HostID: "h1", Why: "why text"}},
		Mitigations: []string{evil},
		Citations:   []string{evil, "no-such-section"},
	})
}

// Every section that renders model text carries its own LLM label, not
// only the one of the Model text section (ADR 0016 D8).
func TestAssistantEveryModelTextSectionCarriesLLMLabel(t *testing.T) {
	summary := opsnotes.Note{ID: 9, Kind: opsnotes.KindSummary, Body: opsnotes.Body{Text: "panel summary"}}
	store := &fakeOpsStore{notes: []opsnotes.Note{modelTextCard(), summary}}
	h := assistantServer(t, assistantOps(store, newCatalog()), assistantUser{"root"})
	body := doAssistant(t, h, http.MethodGet, "/assistant/ops", nil).Body.String()
	for _, label := range []string{"Summary", "Model text", "How to fix", "Sources"} {
		sec, ok := sectionOf(body, label)
		if !ok {
			t.Errorf("section %q missing", label)
			continue
		}
		for _, want := range []string{llmLabelEN, llmLabelDE} {
			if !strings.Contains(sec, want) {
				t.Errorf("section %q: LLM label %q missing", label, want)
			}
		}
	}
}

// Model text in the mitigations and the citation labels is escaped text in
// its section, never markup.
func TestAssistantMitigationsAndCitationsAreEscaped(t *testing.T) {
	store := &fakeOpsStore{notes: []opsnotes.Note{modelTextCard()}}
	h := assistantServer(t, assistantOps(store, newCatalog()), assistantUser{"root"})
	body := doAssistant(t, h, http.MethodGet, "/assistant/ops", nil).Body.String()
	if strings.Contains(body, "<img src=x") {
		t.Error("mitigation or citation rendered as markup")
	}
	for _, label := range []string{"How to fix", "Sources"} {
		sec, _ := sectionOf(body, label)
		if !strings.Contains(sec, "&lt;img src=x onerror=alert(3)&gt;") {
			t.Errorf("section %q: escaped mitigation or citation missing", label)
		}
	}
}

// The panel summary keeps its LLM label and its text stays escaped.
func TestAssistantPanelSummaryKeepsLLMLabel(t *testing.T) {
	store := &fakeOpsStore{notes: []opsnotes.Note{{ID: 9, Kind: opsnotes.KindSummary, Body: opsnotes.Body{Text: "<b>sum</b>"}}}}
	h := assistantServer(t, assistantOps(store, newCatalog()), assistantUser{"root"})
	body := doAssistant(t, h, http.MethodGet, "/assistant/ops", nil).Body.String()
	sec, ok := sectionOf(body, "Summary")
	if !ok {
		t.Fatal("summary section missing")
	}
	for _, want := range []string{llmLabelEN, llmLabelDE, "&lt;b&gt;sum&lt;/b&gt;"} {
		if !strings.Contains(sec, want) {
			t.Errorf("summary section: %q missing", want)
		}
	}
	if strings.Contains(sec, "<b>sum</b>") {
		t.Error("summary text rendered as markup")
	}
}

// An admin's notes must not show up on any Help path: the Help tab, the
// panel shell, the /help page and their htmx forms. The store is not read
// by any of them.
func TestAssistantHelpPathsReturnNoNoteContentForAdmin(t *testing.T) {
	const marker = "NOTEMARK-7731"
	store := &fakeOpsStore{notes: []opsnotes.Note{{
		ID:       1,
		Kind:     opsnotes.KindFix,
		Ref:      "fix:1",
		Digest:   "d1",
		Snapshot: `{"package":"` + marker + `-pkg"}`,
		Body: opsnotes.Body{
			Summary:     marker + " summary",
			Urgency:     marker + " urgency",
			Steps:       []opsnotes.StepInput{{ActionID: marker + "-action", HostID: marker + "-host", Why: marker + " why"}},
			Mitigations: []string{marker + " mitigation"},
			Citations:   []string{marker + " citation"},
		},
		CreatedAt: time.Unix(0, 0),
	}, {ID: 2, Kind: opsnotes.KindSummary, Body: opsnotes.Body{Text: marker + " summary text"}}}}
	h := assistantServer(t, assistantOps(store, newCatalog()), assistantUser{"root"})
	paths := []string{
		"/assistant/panel",
		"/assistant/help",
		// The search text is echoed into the input as the user typed it, so
		// the queries carry no marker; the marker must come from notes only.
		"/assistant/help?q=backup",
		"/assistant/help?q=summary",
		"/help",
		"/help?q=backup",
	}
	for _, path := range paths {
		for _, headers := range []map[string]string{nil, {"HX-Request": "true"}} {
			rec := doAssistant(t, h, http.MethodGet, path, headers)
			if rec.Code != http.StatusOK {
				t.Errorf("GET %s: %d, want 200", path, rec.Code)
			}
			if strings.Contains(rec.Body.String(), marker) {
				t.Errorf("GET %s (htmx=%v) returned note content", path, headers != nil)
			}
		}
	}
	if n := store.readCount(); n != 0 {
		t.Errorf("Help paths read the notes store %d times for an admin, want 0", n)
	}
}

